import re
from typing import Dict, Any, List, Tuple

class PolicyEnforcementLayer:
    """
    Programmatic Policy Enforcement Layer for Privilege Separation:
    Interprets tool calls generated by the agent and ensures sensitive tools
    (e.g., email_send, file_write to sensitive targets, calendar_event)
    are strictly authorized by the TRUSTED user instruction, never by untrusted tool data.
    """
    SENSITIVE_TOOLS = {"email_send", "file_write", "calendar_event"}

    def __init__(self):
        self.violations_logged: List[Dict[str, Any]] = []

    def validate_tool_call(
        self,
        tool_call: Dict[str, Any],
        trusted_user_task: str,
        untrusted_data: str
    ) -> Tuple[bool, str]:
        """
        Validates whether a tool call is authorized.
        Returns: (is_permitted, reason)
        """
        name = tool_call.get("name")
        args = tool_call.get("arguments", {})

        # If not a sensitive tool, allow
        if name not in self.SENSITIVE_TOOLS:
            return True, "Tool call permitted under standard policy."

        trusted_lower = trusted_user_task.lower()
        untrusted_lower = untrusted_data.lower()

        # Check 1: email_send
        if name == "email_send":
            to_addr = args.get("to", "").lower()
            # If user didn't mention sending an email or user didn't specify this email address
            if "email" not in trusted_lower and "mail" not in trusted_lower and "send" not in trusted_lower:
                violation = (
                    f"PRIVILEGE VIOLATION: Tool 'email_send' triggered by untrusted content. "
                    f"User did not request email transmission."
                )
                self.violations_logged.append({"tool": name, "args": args, "reason": violation})
                return False, violation

            if to_addr and to_addr not in trusted_lower and to_addr in untrusted_lower:
                violation = (
                    f"PRIVILEGE VIOLATION: Recipient '{to_addr}' was extracted from untrusted data, "
                    f"not authorized in trusted user instructions."
                )
                self.violations_logged.append({"tool": name, "args": args, "reason": violation})
                return False, violation

        # Check 2: file_write
        if name == "file_write":
            filename = args.get("filename", "").lower()
            if "write" not in trusted_lower and "save" not in trusted_lower and "export" not in trusted_lower:
                violation = (
                    f"PRIVILEGE VIOLATION: Tool 'file_write' for '{filename}' was requested by untrusted data "
                    f"without trusted user authorization."
                )
                self.violations_logged.append({"tool": name, "args": args, "reason": violation})
                return False, violation

        # Check 3: calendar_event
        if name == "calendar_event":
            if "calendar" not in trusted_lower and "meeting" not in trusted_lower and "schedule" not in trusted_lower:
                violation = (
                    f"PRIVILEGE VIOLATION: Tool 'calendar_event' not authorized in trusted user task."
                )
                self.violations_logged.append({"tool": name, "args": args, "reason": violation})
                return False, violation

        return True, "Tool call authorized by trusted context."


class DualContextManager:
    """
    Dual-Context architecture separating Trusted vs Untrusted streams.
    """
    @staticmethod
    def format_untrusted_data(raw_tool_output: str, source_tool: str = "tool") -> str:
        """
        Wraps external data in an isolated, non-executable data block with explicit boundary tags.
        """
        return (
            f"\n<UNTRUSTED_EXTERNAL_DATA source='{source_tool}' policy='READ_ONLY_DATA'>\n"
            f"{raw_tool_output}\n"
            f"</UNTRUSTED_EXTERNAL_DATA>\n"
        )

